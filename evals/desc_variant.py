#!/usr/bin/env python3
"""Load a description variant. Callers pass an id; this module owns the file.

``current`` (the default) means the shipped strings in ``src/server.rs``.
The harness does not copy those strings and does not set
``SPEEDREAD_DESCRIPTION_FILE``, so an unmodified ``speedread mcp`` answers
``tools/list``.

Any other id is ``evals/descriptions/<id>.json``. That file is the only owner
of the variant text. The server applies it only when the env var points at
the file. There is no lean default in this directory: the sibling track drops
``lean.json`` here later.
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DESCRIPTIONS = HERE / "descriptions"
CURRENT = "current"
ENV = "SPEEDREAD_DESCRIPTION_FILE"
RSS_ENV = "SPEEDREAD_RSS_LOG"

_ALLOWED_TOOLS = {"read", "search", "map", "trace"}


def variant_path(variant_id):
    if variant_id in (None, "", CURRENT):
        return None
    path = DESCRIPTIONS / f"{variant_id}.json"
    if not path.is_file():
        raise SystemExit(
            f"no description variant {variant_id!r} at {path}. "
            f"Shipped text is {CURRENT!r}, which is not a file. "
            f"A shorter text from the sibling track belongs at {DESCRIPTIONS / 'lean.json'}."
        )
    return path


def load_variant(variant_id):
    """Return the parsed file, or None for the shipped defaults."""
    path = variant_path(variant_id)
    if path is None:
        return None
    try:
        doc = json.loads(path.read_text())
    except json.JSONDecodeError as e:
        raise SystemExit(f"{path}: {e}") from e
    if not isinstance(doc, dict):
        raise SystemExit(f"{path}: expected a JSON object")
    extra = set(doc) - {"instructions", "tools"}
    if extra:
        raise SystemExit(f"{path}: unknown keys {sorted(extra)}")
    tools = doc.get("tools") or {}
    if not isinstance(tools, dict) or any(not isinstance(k, str) or not isinstance(v, str) or not k or not v for k, v in tools.items()):
        raise SystemExit(f"{path}: \"tools\" must be a map of non-empty name → non-empty description")
    unknown = sorted(set(tools) - _ALLOWED_TOOLS)
    # Future speedread tools are allowed only when the server has them. The
    # server rejects unknown names at startup. Keep the harness check to the
    # four tools that exist today so a typo fails before a live trial.
    if unknown:
        raise SystemExit(f"{path}: unknown tool names {unknown}; known tools are {sorted(_ALLOWED_TOOLS)}")
    instructions = doc.get("instructions")
    if instructions is not None and not isinstance(instructions, str):
        raise SystemExit(f"{path}: \"instructions\" must be a string")
    if instructions is None and not tools:
        raise SystemExit(f"{path}: set instructions or tools; an empty variant would silently match {CURRENT}")
    return doc


def description_env(variant_id, rss_log=None):
    """Env for the speedread process. ``current`` sets no description variable."""
    env = {}
    path = variant_path(variant_id)
    if path is not None:
        load_variant(variant_id)  # fail before a trial if the file is bad
        env[ENV] = str(path.resolve())
    if rss_log:
        env[RSS_ENV] = str(rss_log)
    return env


def toml_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def grok_config(speedread_bin, variant_id, rss_log=None):
    """Project-independent user config that launches this binary and nothing else."""
    env = description_env(variant_id, rss_log=rss_log)
    lines = [
        "# Generated by evals/desc_variant.py for one trial. Not a product default.",
        "[mcp_servers.speedread]",
        f"command = {toml_string(str(Path(speedread_bin).resolve()))}",
        'args = ["mcp"]',
        "startup_timeout_sec = 120",
        "tool_timeout_sec = 600",
    ]
    if env:
        pairs = ", ".join(f"{k} = {toml_string(v)}" for k, v in sorted(env.items()))
        lines.append(f"env = {{ {pairs} }}")
    return "\n".join(lines) + "\n"


def copilot_mcp_config(speedread_bin, variant_id, rss_log=None):
    """MCP config for ``copilot --additional-mcp-config``. ``current`` has no description env."""
    server = {
        "type": "local",
        "command": str(Path(speedread_bin).resolve()) if speedread_bin else "speedread",
        "args": ["mcp"],
        "tools": ["*"],
    }
    env = description_env(variant_id, rss_log=rss_log)
    if env:
        server["env"] = env
    return {"mcpServers": {"speedread": server}}
